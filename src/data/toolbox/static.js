export function lookupMime(query) {
  const text = String(query ?? '').trim().toLowerCase()
  if (!text) return []
  const extension = text.includes('.') && !text.includes('/') ? text.split('.').pop() : text
  const results = MIME_TYPES.filter(
    (item) =>
      item.mime.toLowerCase() === text ||
      item.ext.includes(extension) ||
      item.mime.toLowerCase().includes(text) ||
      item.description.includes(text)
  )
  return results.sort((a, b) => {
    const aExact = a.ext.includes(extension) || a.mime.toLowerCase() === text ? -1 : 0
    const bExact = b.ext.includes(extension) || b.mime.toLowerCase() === text ? -1 : 0
    return aExact - bExact
  })
}

